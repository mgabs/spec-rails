import { afterEach, beforeEach, describe, expect, it } from "vitest";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { main, upgrade } from "../../scripts/upgrade-openspec.mjs";

const repo = path.resolve(__dirname, "../..");
const read = (...p: string[]) => fs.readFileSync(path.join(repo, ...p), "utf8");
const lsDirs = (dir: string) =>
  fs.readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name);

const PORTS: Record<string, string> = {
  explore: "openspec-explore",
  propose: "openspec-propose",
  apply: "openspec-apply-change",
  archive: "openspec-archive-change",
  sync: "openspec-sync-specs",
  update: "openspec-update-change",
};
const pin = read("openspec-version").trim();
const snapshot = path.join(repo, "vendor", "openspec", pin);

function frontmatter(text: string): Record<string, string> {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  const out: Record<string, string> = {};
  for (const line of (m?.[1] ?? "").split("\n")) {
    const kv = /^([\w-]+):\s*(.*)$/.exec(line);
    if (kv) out[kv[1]] = kv[2];
  }
  return out;
}

describe("REQ-POS-1 single pinned version", () => {
  it("openspec-version holds exactly one semver", () => {
    expect(read("openspec-version")).toMatch(/^\d+\.\d+\.\d+\n$/);
  });

  it("no other file hard-codes the pinned OpenSpec version", () => {
    const r = spawnSync("grep", ["-rlF", pin, "src", "templates", "skills", "scripts", "rules", "schemas"], {
      cwd: repo,
      encoding: "utf8",
    });
    expect(r.stdout.split("\n").filter((f) => f && !f.startsWith("skills/ports/"))).toEqual([]);
  });
});

describe("REQ-POS-2 CLI-free skills", () => {
  for (const wf of Object.keys(PORTS)) {
    const body = fs.existsSync(path.join(repo, "skills/ports", `${wf}.md`)) ? read("skills/ports", `${wf}.md`) : "";
    it(`REQ-POS-2 ${wf} port has no openspec invocation`, () => {
      expect(body).not.toBe("");
      expect(body).not.toMatch(/openspec\s/);
      expect(body).not.toContain("Bash(openspec");
    });
    it(`REQ-POS-2 ${wf} port is invocable and well-formed`, () => {
      expect(body).not.toMatch(/user-invocable:\s*false/);
      const fm = frontmatter(body);
      expect(fm.workflow).toBe(wf);
    });
  }
});

describe("REQ-POS-3 reference snapshot", () => {
  it("snapshot dir matches the pin and no other version exists", () => {
    expect(fs.existsSync(snapshot)).toBe(true);
    expect(lsDirs(path.join(repo, "vendor", "openspec"))).toEqual([pin]);
  });

  it("snapshot is not shipped into target repos by templates", () => {
    expect(fs.existsSync(path.join(repo, "templates", "vendor"))).toBe(false);
  });
});

describe("REQ-POS-5 drift check", () => {
  const upstream = lsDirs(path.join(snapshot, ".agents", "skills")).sort();
  const excluded = read("skills/ports/EXCLUDED.md");
  const ported = new Set(Object.values(PORTS));

  it("every upstream skill is ported or documented as excluded", () => {
    const missing = upstream.filter((s) => !ported.has(s) && !excluded.includes(`\`${s}\``));
    expect(missing, `no shipped counterpart or exclusion for: ${missing.join(", ")}`).toEqual([]);
  });

  it("every port maps to an upstream skill", () => {
    for (const skill of ported) expect(upstream).toContain(skill);
  });

  it("every port records the pinned version it was ported from", () => {
    for (const wf of Object.keys(PORTS)) {
      expect(frontmatter(read("skills/ports", `${wf}.md`)).portedFrom, wf).toBe(pin);
    }
  });

  it("snapshot skills were generated by the pinned version", () => {
    for (const s of upstream) {
      expect(read("vendor/openspec", pin, ".agents/skills", s, "SKILL.md")).toContain(`generatedBy: "${pin}"`);
    }
  });
});

describe("REQ-POS-4 upgrade script", () => {
  let root: string;
  let shimDir: string;
  let out: string[];
  let errs: string[];
  const env = process.env;

  const run = (version: string, npx = path.join(shimDir, "npx")) =>
    upgrade({ version, root, npx, out: (s: string) => out.push(s), err: (s: string) => errs.push(s) });
  const tree = (dir: string): string[] =>
    fs.existsSync(dir)
      ? fs.readdirSync(dir, { recursive: true, withFileTypes: true }).filter((e) => e.isFile()).map((e) =>
          path.join(e.parentPath, e.name),
        ).sort()
      : [];
  const dump = () => tree(root).map((f) => `${path.relative(root, f)}\n${fs.readFileSync(f, "utf8")}`).join("\n--\n");

  beforeEach(() => {
    root = fs.mkdtempSync(path.join(os.tmpdir(), "spec-rails-upgrade-"));
    shimDir = fs.mkdtempSync(path.join(os.tmpdir(), "spec-rails-shim-"));
    out = [];
    errs = [];
    const shim = path.join(shimDir, "npx");
    fs.writeFileSync(
      shim,
      [
        "#!/bin/sh",
        'printf "%s\\n" "$0" "$(basename "$PWD")" "$@" > "$FAKE_NPX_LOG"',
        'case "$FAKE_NPX_MODE" in fail) echo "404 not found" >&2; exit 1;; empty) exit 0;; esac',
        'v=$(echo "$2" | sed "s/.*@//")',
        "for d in .agents .claude .github; do",
        '  mkdir -p "$d/skills/openspec-explore"',
        '  printf "generatedBy: %s\\n%s\\n" "$v" "${FAKE_NPX_BODY:-body}" > "$d/skills/openspec-explore/SKILL.md"',
        "done",
        "",
      ].join("\n"),
      { mode: 0o755 },
    );
    fs.writeFileSync(path.join(root, "openspec-version"), "1.16.0\n");
    fs.mkdirSync(path.join(root, "skills/ports"), { recursive: true });
    fs.writeFileSync(path.join(root, "skills/ports/explore.md"), "shipped\n");
    process.env = { ...env, FAKE_NPX_LOG: path.join(shimDir, "log") };
  });

  afterEach(() => {
    process.env = env;
    fs.rmSync(root, { recursive: true, force: true });
    fs.rmSync(shimDir, { recursive: true, force: true });
  });

  it("REQ-POS-4 creates the snapshot when none exists", () => {
    expect(run("1.16.0")).toBe(0);
    expect(out).toEqual(["No previous snapshot; created vendor/openspec/1.16.0."]);
    const [, cwdName, ...args] = fs.readFileSync(path.join(shimDir, "log"), "utf8").trim().split("\n");
    expect(cwdName).toMatch(/^\.upgrade-/);
    expect(args.slice(0, -1)).toEqual([
      "--yes", "@fission-ai/openspec@1.16.0", "init", "--tools", "agents,github-copilot,claude", "--no-copilot-cloud", "--no-animation",
    ]);
    expect(path.basename(args.at(-1)!)).toBe(cwdName);
    expect(fs.existsSync(path.join(root, "vendor/openspec/1.16.0/.claude/skills/openspec-explore/SKILL.md"))).toBe(true);
    expect(fs.readdirSync(root).filter((n) => n.startsWith(".upgrade-"))).toEqual([]);
  });

  it("REQ-POS-4 upgrade to a new version swaps vendor dir, pin, prints diff, leaves ports alone", () => {
    run("1.16.0");
    process.env.FAKE_NPX_BODY = "changed body";
    out.length = 0;
    expect(run("1.17.0")).toBe(0);
    expect(fs.readFileSync(path.join(root, "openspec-version"), "utf8")).toBe("1.17.0\n");
    expect(lsDirs(path.join(root, "vendor/openspec"))).toEqual(["1.17.0"]);
    expect(typeof out[0]).toBe("string");
    expect(out[0]).toMatch(/-body[\s\S]*\+changed body/);
    expect(fs.readFileSync(path.join(root, "skills/ports/explore.md"), "utf8")).toBe("shipped\n");
  });

  it("REQ-POS-4 re-run with the same version changes nothing under vendor", () => {
    run("1.16.0");
    out.length = 0;
    const before = dump();
    expect(run("1.16.0")).toBe(0);
    expect(dump()).toBe(before);
    expect(out).toEqual(["No upstream skill changes versus 1.16.0."]);
  });

  it("REQ-POS-4 unknown version exits non-zero and changes no file", () => {
    run("1.16.0");
    const before = dump();
    process.env.FAKE_NPX_MODE = "fail";
    expect(run("9.9.9")).toBe(1);
    expect(errs).toEqual(["fetch/generate failed for 9.9.9: 404 not found\n"]);
    expect(dump()).toBe(before);
  });

  it("REQ-POS-4 missing npx binary fails without changes", () => {
    const before = dump();
    expect(run("1.16.0", path.join(shimDir, "nope"))).toBe(1);
    expect(errs[0]).toMatch(/^fetch\/generate failed for 1\.16\.0: .*ENOENT/);
    expect(dump()).toBe(before);
  });

  it("REQ-POS-4 upstream generating no skills fails without changes", () => {
    process.env.FAKE_NPX_MODE = "empty";
    const before = dump();
    expect(run("1.16.0")).toBe(1);
    expect(errs).toEqual(["OpenSpec 1.16.0 generated no skills; nothing changed"]);
    expect(dump()).toBe(before);
  });

  it("REQ-POS-4 rejects a non-semver version", () => {
    expect(run("latest")).toBe(2);
    expect(run(undefined as unknown as string)).toBe(2);
    expect(errs[0]).toBe("usage: upgrade-openspec.mjs <x.y.z>");
  });

  it("REQ-POS-4 only the snapshot pieces for the three agent layouts are vendored", () => {
    run("1.16.0");
    expect(fs.readdirSync(path.join(root, "vendor/openspec/1.16.0")).sort()).toEqual([".agents", ".claude", ".github"]);
  });

  it("REQ-POS-4 main uses SPEC_RAILS_NPX when set and npx from PATH otherwise", () => {
    const custom = path.join(shimDir, "custom-npx");
    fs.copyFileSync(path.join(shimDir, "npx"), custom);
    fs.chmodSync(custom, 0o755);
    const logged = () => fs.readFileSync(path.join(shimDir, "log"), "utf8").split("\n")[0];
    expect(main(["node", "x", "1.16.0"], { SPEC_RAILS_NPX: custom }, root)).toBe(0);
    expect(path.basename(logged())).toBe("custom-npx");
    process.env.PATH = `${shimDir}${path.delimiter}${env.PATH}`;
    expect(main(["node", "x", "1.16.0"], {}, root)).toBe(0);
    expect(path.basename(logged())).toBe("npx");
    expect(main(["node", "x", "1.16.0"], { SPEC_RAILS_NPX: "" }, root)).toBe(0);
    expect(path.basename(logged())).toBe("npx");
  });
});
